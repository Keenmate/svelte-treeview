#!/usr/bin/env node
// Regenerates src/routes/(showcase)/examples/theme-comparison/<theme>.css from the compiled
// pure-admin themes (../pure-admin-themes/<theme>/dist/<theme>.css).
//
// Takes the --base-* declarations a theme emits at :root plus its top-level
// .pc-mode-<mode> block (later wins), keeps only names in the canonical contract
// (../base-css-variables/base-variables.css), and scopes them to .theme-<name>.
// Derived tokens stay formulas (var()/color-mix/oklch), so they resolve against
// the scope's own inputs. --base-rem is pinned to 10px for the 16px-root page.
//
//   node scripts/extract-theme-tokens.mjs            # all themes below
//   PURE_ADMIN_THEMES_DIR=… node scripts/extract-theme-tokens.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const themesDir = process.env.PURE_ADMIN_THEMES_DIR || path.resolve(root, '../pure-admin-themes');
const contractFile = path.resolve(root, '../base-css-variables/base-variables.css');
const outDir = path.join(root, 'src/routes/(showcase)/examples/theme-comparison');

// theme → mode the showcase renders it in
const THEMES = {
	cobalt2: { mode: 'dark', label: 'COBALT2' },
	dracula: { mode: 'dark', label: 'DRACULA' },
	corporate: { mode: 'light', label: 'CORPORATE' }
};

const contract = new Set(
	[...readFileSync(contractFile, 'utf8').matchAll(/--(base-[a-z0-9-]+)\s*:/g)].map((m) => m[1])
);

// Top-level rules only: walk the stylesheet tracking brace depth.
function topLevelRules(css) {
	css = css.replace(/\/\*[\s\S]*?\*\//g, '');
	const rules = [];
	let depth = 0, start = 0, selector = '';
	for (let i = 0; i < css.length; i++) {
		const ch = css[i];
		if (ch === '{') {
			if (depth === 0) { selector = css.slice(start, i).trim(); start = i + 1; }
			depth++;
		} else if (ch === '}') {
			depth--;
			if (depth === 0) { rules.push({ selector, body: css.slice(start, i) }); start = i + 1; }
		}
	}
	return rules;
}

function declarations(body) {
	// strip nested blocks, keep this rule's own declarations
	let flat = '', depth = 0;
	for (const ch of body) {
		if (ch === '{') depth++;
		else if (ch === '}') depth--;
		else if (depth === 0) flat += ch;
	}
	const out = [];
	for (const m of flat.matchAll(/(--[a-z0-9-]+|color-scheme)\s*:\s*([^;]+);?/g)) out.push([m[1], m[2].trim()]);
	return out;
}

for (const [name, { mode, label }] of Object.entries(THEMES)) {
	const src = path.join(themesDir, name, 'dist', `${name}.css`);
	const css = readFileSync(src, 'utf8');
	const wanted = (sel) =>
		sel.split(',').map((s) => s.trim()).some((s) => s === ':root' || s === `.pc-mode-${mode}`);
	const tokens = new Map();
	let scheme = mode;
	for (const rule of topLevelRules(css)) {
		if (!wanted(rule.selector)) continue;
		for (const [prop, value] of declarations(rule.body)) {
			if (prop === 'color-scheme') { scheme = value.split(/\s+/)[0]; continue; }
			const n = prop.slice(2);
			if (contract.has(n)) tokens.set(n, value);
		}
	}
	tokens.set('base-rem', '10px');
	const body = [...tokens].map(([n, v]) => `\t--${n}: ${v};`).join('\n');
	const out = `/* =============================================================================
   ${label} THEME — extracted --base-* design tokens
   =============================================================================
   Generated by scripts/extract-theme-tokens.mjs from @keenmate/pure-admin-theme-${name}
   (${mode} mode). Scoped to .theme-${name} so the tokens flow into BOTH
   <web-multiselect> (via :host inheritance) and <Tree> (.stv__container).
   --base-rem pinned to 10px for the 16px-root showcase. Do not edit by hand. */
.theme-${name} {
\tcolor-scheme: ${mode === 'dark' ? 'dark' : 'light'};
${body}
}
`;
	writeFileSync(path.join(outDir, `${name}.css`), out);
	console.log(`${name}: ${tokens.size} tokens (${mode}${scheme !== mode ? `, theme color-scheme ${scheme}` : ''})`);
}
